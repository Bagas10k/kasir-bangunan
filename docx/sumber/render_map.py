#!/usr/bin/env python3
"""Validate a local flow model and render its Markdown map (Python 3.8+).

CLI paths are relative to the working directory; evidence is relative to --root.
Array order is authored order. Table keys sort by Unicode code point. Output is
UTF-8 with LF endings. Run against a local workspace with trusted directories;
serialize writes to the same map. No Mermaid runtime is loaded or executed.
"""
import argparse
import json
import os
from pathlib import Path, PureWindowsPath
import re
import stat
import sys
import unicodedata


MARKER = '<!-- Generated by peta-alur-hidup/render.py; do not edit. -->'
IDENTIFIER = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')
DEVICE = re.compile(r'(?:CON|PRN|AUX|NUL|CONIN\$|CONOUT\$|(?:COM|LPT)[0-9¹²³])(?:\.|$)', re.I)


def require(ok, message):
    if not ok:
        raise ValueError(message)


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, f'duplicate JSON key: {key!r}')
        result[key] = value
    return result


def fields(obj, names, where):
    require(isinstance(obj, dict) and set(obj) == set(names.split()),
            f'{where}: expected exactly these fields: {names}')


def text(value, where):
    require(isinstance(value, str), f'{where}: expected a string')
    return value


def safe_component(part):
    return (part not in ('', '.', '..') and not part.endswith((' ', '.'))
            and not re.search(r'[<>:"/\\|?*\x00-\x1f]', part)
            and not DEVICE.match(part.split('.')[0].rstrip(' ')))


def local_path(raw):
    win = PureWindowsPath(raw)
    require(not win.drive.startswith('\\\\') and not (win.drive and not win.root),
            f'not a local path: {raw!r}')
    path = Path(raw).absolute()
    require(all(safe_component(p) for p in path.parts[1:]), f'unsafe path: {raw!r}')
    return path


def inspect(path):
    info = path.lstat()
    require(not stat.S_ISLNK(info.st_mode) and not
            (getattr(info, 'st_file_attributes', 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT),
            f'links are not allowed: {path}')
    return info


def directory(path, create=False):
    for parent in (*reversed(path.parents), path):
        try:
            info = inspect(parent)
        except FileNotFoundError:
            if not create:
                raise
            parent.mkdir()
            info = inspect(parent)
        require(stat.S_ISDIR(info.st_mode), f'not a directory: {parent}')


def regular(path):
    info = inspect(path)
    require(stat.S_ISREG(info.st_mode), f'not a regular file: {path}')
    return info


def evidence(ref, root, where):
    name, colon, line = ref.rpartition(':')
    parts = re.split(r'[/\\]', name)
    require(colon and re.fullmatch(r'[1-9][0-9]*', line) and all(map(safe_component, parts)),
            f'{where}: expected relative/file:positive-line, got {ref!r}')
    return root.joinpath(*parts), int(line)


def validate(model, root):
    fields(model, 'title steps edges unknowns', 'model')
    text(model['title'], 'title')
    for name in ('steps', 'edges', 'unknowns'):
        require(isinstance(model[name], list), f'{name}: expected an array')
    ids, refs = set(), {}
    for n, step in enumerate(model['steps']):
        where = f'steps[{n}]'
        fields(step, 'id label actor before after evidence tables', where)
        for key in ('id', 'label', 'actor', 'before', 'after', 'evidence'):
            text(step[key], f'{where}.{key}')
        sid = step['id']
        require(IDENTIFIER.fullmatch(sid) and sid not in ids, f'{where}: invalid or duplicate id {sid!r}')
        ids.add(sid)
        require(isinstance(step['tables'], dict), f'{where}.tables: expected an object')
        for key, ops in step['tables'].items():
            require(key.strip(), f'{where}.tables: empty table name')
            text(ops, f'{where}.tables[{key!r}]')
            require(all(op.strip() in {'read', 'create', 'update', 'delete'} for op in ops.split(',')), f'{where}.tables: unknown operation')
        path, line = evidence(step['evidence'], root, where)
        if path not in refs or line > refs[path][0]:
            refs[path] = line, where
    for n, edge in enumerate(model['edges']):
        where = f'edges[{n}]'
        fields(edge, 'from to label', where)
        text(edge['label'], where + '.label')
        for key in ('from', 'to'):
            require(text(edge[key], where + '.' + key) in ids, f'{where}.{key}: unknown step {edge[key]!r}')
    for n, unknown in enumerate(model['unknowns']):
        text(unknown, f'unknowns[{n}]')
    # Checking the highest requested line proves every lower line exists too.
    for path, (line, where) in refs.items():
        directory(path.parent)
        regular(path)
        with path.open(encoding='latin-1', newline=None) as source:
            for number, _ in enumerate(source, 1):
                if number == line:
                    break
            else:
                raise ValueError(f'{where}: no line {line} in {path.relative_to(root)}')


def visible(value):
    # Collapse layout and spell out controls, including bidi overrides/surrogates.
    return ' '.join(''.join(f'U+{ord(c):04X}' if unicodedata.category(c) in ('Cc', 'Cf', 'Cs')
                            else c for c in word) for word in value.split())


def md(value):
    return ''.join(c if c.isalnum() or c in ' .' else f'&#{ord(c)};' for c in visible(value))


def graph(value):
    # Do not decode user-controlled HTML entities in a downstream SVG/HTML
    # renderer. Use visible code points for syntax; the table retains the text.
    return ''.join(c if c.isalnum() or c in ' _.,:()-' else f' U+{ord(c):04X} '
                   for c in visible(value))


def row(*cells):
    return '| ' + ' | '.join(md(cell) for cell in cells) + ' |'


def render(model):
    out = [MARKER, '', '# ' + md(model['title']), '', '```mermaid', 'flowchart TD']
    reverse = {}
    for step in model['steps']:
        sid = step['id']
        out.append(f'    n_{sid}["{graph(step["label"]) or sid}"]')
    for edge in model['edges']:
        label = graph(edge['label'])
        arrow = f'-->|"{label}"|' if label else '-->'
        out.append(f'    n_{edge["from"]} {arrow} n_{edge["to"]}')
    out += ['```', '', '## Rincian langkah', '', '| ID | Langkah | Pelaku | Syarat awal | Hasil | Bukti kode | Tabel |',
            '| --- | --- | --- | --- | --- | --- | --- |']
    for step in model['steps']:
        tables = []
        for table, ops in sorted(step['tables'].items()):
            reverse.setdefault(table, []).append((step['id'], ops))
            tables.append(f'{table}: {ops}')
        out.append(row(*(step[k] for k in ('id', 'label', 'actor', 'before', 'after', 'evidence')),
                       '; '.join(tables)))
    out += ['', '## Indeks tabel', '', '| Tabel | Langkah | Operasi |', '| --- | --- | --- |']
    for table, uses in sorted(reverse.items()):
        out.extend(row(table, sid, ops) for sid, ops in uses)
    out += ['', '## Batas analisis', '']
    out.extend(['- ' + md(u) for u in model['unknowns']] or ['Tidak ada keterbatasan yang dicatat.'])
    return ('\n'.join(out) + '\n').encode('utf-8')


def publish(path, data, check):
    try:
        directory(path.parent, create=not check)
        info = regular(path)
    except FileNotFoundError:
        if check:
            return False
        # Exclusive creation cannot follow an existing final link or clobber a file.
        with path.open('xb') as dest:
            dest.write(data)
        return True
    flags = (os.O_RDONLY if check else os.O_RDWR) | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_BINARY', 0)
    with os.fdopen(os.open(path, flags), 'rb' if check else 'r+b') as dest:
        opened = os.fstat(dest.fileno())
        require(os.path.samestat(info, opened) and opened.st_nlink == 1, f'linked or changed output: {path}')
        marker = MARKER.encode('ascii')
        first = dest.readline(len(marker) + 3)
        require(first in (marker, marker + b'\n', marker + b'\r\n'), f'refusing unmarked output: {path}')
        dest.seek(0)
        same = opened.st_size == len(data) and dest.read(len(data)) == data
        if check or same:
            return same
        # Write only through the descriptor whose ownership marker we verified.
        dest.seek(0)
        dest.write(data)
        dest.truncate()
        return True


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('model', metavar='MODEL.json')
    cli.add_argument('--root', required=True, metavar='PROJECT')
    cli.add_argument('--output', required=True, metavar='MAP.md')
    cli.add_argument('--check', action='store_true', help='compare exact bytes without writing')
    args = cli.parse_args()
    try:
        root, source, output = map(local_path, (args.root, args.model, args.output))
        directory(root)
        require(output.is_relative_to(root) and output.suffix.lower() == '.md', 'output must be a Markdown file inside --root')
        directory(source.parent)
        regular(source)
        model = json.loads(source.read_text(encoding='utf-8-sig'), object_pairs_hook=unique_object)
        validate(model, root)
        if not publish(output, render(model), args.check):
            print('missing or stale map:', output, file=sys.stderr)
            return 1
        return 0
    except (OSError, ValueError, RecursionError) as exc:
        print('render:', ascii(str(exc)), file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())
