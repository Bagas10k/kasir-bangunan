SCALARS = {'int', 'float', 'string', 'bool', 'array', 'mixed', 'object', 'callable', 'self', 'static', 'null'}


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def json_bytes(data) -> bytes:
    return (json.dumps(data, ensure_ascii=False, separators=(',', ':')) + '\n').encode('utf-8')

def diagram_markdown(journeys):
    """Readable business diagrams with source evidence, never a function-call graph."""
    output = ['<!-- Generated by docx/live.py; edit sumber/alur-operasional.json instead. -->',
              '# Diagram alur sistem Kasir Bangunan', '',
              'Alur bisnis dari kode working tree. Pilihan/cabang bukan urutan wajib. Bukti kode ada per tahap.', '',
              'Cakupan: operasional V2. Konfigurasi runtime, database, deployment dan alur V1 tidak diuji.', '',
              'Batas penting: draf belum mengubah stok; final penerimaan menambah stok/utang tanpa kas keluar; transfer menunggu bukan uang bank yang sudah dibukukan.', '']
    def label(text):
        return str(text).replace('&', '&amp;').replace('"', '&quot;').replace('<', '&lt;').replace('>', '&gt;').replace('\n', ' ')
    for journey in journeys:
        output.extend(['## '+journey['title'], '', journey['start'], '', '```mermaid', 'flowchart TD'])
        ids = {s['id']: 'n'+str(i) for i,s in enumerate(journey['steps'])}
        for stage in journey['steps']:
            content = label(stage['title'])
            if stage['kind'] == 'decision':
                output.append(f'    {ids[stage["id"]]}{{"{content}"}}')
            else:
                output.append(f'    {ids[stage["id"]]}["{content}"]')
        end_number = 0
        for stage in journey['steps']:
            source = ids[stage['id']]
            branch_targets = set()
            for branch in stage['branches']:
                target = branch['next']
                if target:
                    branch_targets.add(target)
                    destination = ids[target]
                else:
                    destination = 'end'+str(end_number)
                    output.append(f'    {destination}(["Cabang selesai"])')
                    end_number += 1
                output.append(f'    {source} -->|"{label(branch["label"])}"| {destination}')
            for target in stage['next']:
                if target not in branch_targets:
                    connector = '-->|"Opsional"|' if len(stage['next']) > 1 else '-->'
                    output.append(f'    {source} {connector} {ids[target]}')
        output.extend(['```', '', '| Tahap | Pelaku | Bukti sumber |', '| --- | --- | --- |'])
        for stage in journey['steps']:
            refs = '; '.join(f'{e["path"]}:{e["line"]}-{e["end"]}' for e in stage['evidence'])
            output.append('| '+stage['title']+' | '+stage['actor']+' | '+refs+' |')
        output.extend(['', 'Hasil: '+journey['finish'], ''])
    return ('\n'.join(output)+'\n').encode('utf-8')


def load_sync(root):
    spec = importlib.util.spec_from_file_location('documentation_source_scope', OUT / 'sinkron.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.ROOT, module.OUT = root, root / 'docx'
    return module


def tokenize(source):
    starts = [0] + [m.end() for m in re.finditer('\n', source)]
    return [(m.group(), m.start(), m.end(), bisect_right(starts, m.start()), m.lastgroup)
            for m in TOKEN_PATTERN.finditer(source) if m.lastgroup not in ('space', 'comment')]


def matching(tokens, start, opener='(', closer=')'):
    level = 0
    for i in range(start, len(tokens)):
        if tokens[i][0] == opener:
            level += 1
        elif tokens[i][0] == closer:
            level -= 1
            if level == 0:
                return i
    raise ValueError(f'Tanda {opener}{closer} belum lengkap pada baris {tokens[start][3]}')


def literal(token):
    if token[4] != 'string':
        return None
    return token[0][1:-1].replace('\\\\', '\\').replace("\\'", "'")


def imports(source):
    result = {}
    for match in re.finditer(r'(?:^|[;\n])\s*use\s+([A-Za-z_\\][\w\\]*)(?:\s+as\s+(\w+))?\s*;', source, re.M):
        full, alias = match.groups()
        result[alias or full.split('\\')[-1]] = full
    return result


def resolve_class(name, namespace, aliases):
    if name.startswith('\\'):
        return name.lstrip('\\')
    first, *tail = name.split('\\')
    if first in aliases:
        return '\\'.join([aliases[first], *tail])
    return namespace + '\\' + name if namespace else name


def parameter_types(tokens, namespace, aliases):
    types = {}
    for i, token in enumerate(tokens):
        if token[4] == 'var' and i and tokens[i-1][4] == 'name':
            name = tokens[i-1][0]
            if name not in SCALARS:
                types[token[0]] = resolve_class(name, namespace, aliases)
    return types


def safe_code(code):
    # Source remains verbatim except literal identities/secrets; never expose seeded credentials.
    redactions = []
    for match in re.finditer(r'[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}', code):
        redactions.append((match.start(), match.end(), '[REDACTED]'))
    tokens = tokenize(code)
    for i, token in enumerate(tokens):
        key = (literal(token) if token[4] == 'string' else token[0].lstrip('$')).lower()
        if not re.fullmatch(r'(?:password|secret|token|api_key|app_key|private_key)', key):
            continue
        if i+1 >= len(tokens) or tokens[i+1][0] not in ('=', '=>'):
            continue
        depth = 0
        for rhs in tokens[i+2:]:
            if rhs[0] in (';', ',') and depth == 0:
                break
            if rhs[0] in ('(', '['):
                depth += 1
            elif rhs[0] in (')', ']'):
                depth -= 1
                if depth < 0:
                    break
            if rhs[4] == 'string' and literal(rhs) not in ('password', 'secret', 'token', 'api_key'):
                redactions.append((rhs[1], rhs[2], "'[REDACTED]'"))
    nonoverlapping = []
    for start, end, replacement in sorted(set(redactions), key=lambda item: (item[0], -item[1])):
        if nonoverlapping and start < nonoverlapping[-1][1]:
            continue
        nonoverlapping.append((start, end, replacement))
    for start, end, replacement in reversed(nonoverlapping):
        code = code[:start] + replacement + code[end:]
    return code


def parse_file(path, source):
    tokens = tokenize(source)
    aliases = imports(source)
    namespace_match = re.search(r'\bnamespace\s+([\w\\]+)\s*;', source)
    namespace = namespace_match[1] if namespace_match else ''
    symbols, properties = {}, {}
    i = 0
    while i < len(tokens):
        if tokens[i][0] != 'class' or (i and tokens[i-1][0] == '::') or i+1 >= len(tokens) or tokens[i+1][4] != 'name':
            i += 1
            continue
        class_name = resolve_class(tokens[i+1][0], namespace, {})
        start = next((j for j in range(i+2, len(tokens)) if tokens[j][0] == '{'), None)
        if start is None:
            raise ValueError(f'{path}: badan class belum lengkap')
        finish = matching(tokens, start, '{', '}')
        depth, j, constants = 1, start+1, {}
        while j < finish:
            value = tokens[j][0]
            if value == 'const' and depth == 1 and j+3 < finish and tokens[j+2][0] == '=':
                name, raw = tokens[j+1][0], literal(tokens[j+3])
                if raw is not None:
                    constants[name] = {'value': '[REDACTED]' if re.search('password|secret|token|private_key|api_key', name, re.I) else safe_code(raw), 'line': tokens[j][3]}
            if value == 'function' and depth == 1 and j+2 < finish and tokens[j+1][4] == 'name':
                method = tokens[j+1][0]
                paren = j+2
                if tokens[paren][0] != '(':
                    j += 1
                    continue
                pend = matching(tokens, paren)
                brace = next((k for k in range(pend+1, finish+1) if tokens[k][0] in ('{', ';')), finish)
                if tokens[brace][0] == ';':
                    j = brace+1
                    continue
                mend = matching(tokens, brace, '{', '}')
                types = parameter_types(tokens[paren+1:pend], namespace, aliases)
                if method == '__construct':
                    properties[class_name] = types
                line = tokens[j][3]
                modifier = j
                while modifier > 0 and tokens[modifier-1][0] in ('public', 'protected', 'private', 'static', 'final', 'abstract'):
                    modifier -= 1
                line_start = source.rfind('\n', 0, tokens[modifier][1]) + 1
                offset = line_start if not source[line_start:tokens[modifier][1]].strip() else tokens[modifier][1]
                code = safe_code(source[offset:tokens[mend][2]])
                sid = class_name + '::' + method
                symbols[sid] = {
                    'id': sid, 'class_name': class_name, 'method': method, 'path': path,
                    'line': line, 'end': tokens[mend][3], 'code': code,
                    'constants': constants,
                    '_tokens': tokens[brace+1:mend], '_types': types, '_namespace': namespace,
                    '_aliases': aliases, '_source': source,
                }
                j = mend+1
                continue
            depth += 1 if value == '{' else -1 if value == '}' else 0
            j += 1
        i = finish+1
    return symbols, properties


def analyze_symbol(node, properties, symbols):
    tokens = node['_tokens']
    source_lines = node['_source'].splitlines()
    calls, tables, statuses = [], {}, set()
    guards, writes = {}, {}
    for i, token in enumerate(tokens):
        value, _, _, line, kind = token
        if value in GUARDS:
            guards[line] = safe_code(source_lines[line-1].strip())
        if value in WRITE_METHODS and i and tokens[i-1][0] in ('->', '::', '?->'):
            writes[line] = safe_code(source_lines[line-1].strip())
        if kind == 'string' and literal(token) == 'status' and i+2 < len(tokens) and tokens[i+1][0] == '=>':
            if tokens[i+2][4] == 'string':
                statuses.add(literal(tokens[i+2]))
        if value == 'table' and i+2 < len(tokens) and tokens[i+1][0] == '(' and tokens[i+2][4] == 'string':
            table = re.split(r'\s+(?:as\s+)?', literal(tokens[i+2]), flags=re.I)[0]
            operations = {'read'}
            k = i+3
            while k < len(tokens) and tokens[k][0] != ';':
                if tokens[k][0] in WRITE_METHODS:
                    operations.update(WRITE_METHODS[tokens[k][0]].split(','))
                    if 'create' in operations and 'update' not in operations:
                        operations.discard('read')
                    break
                k += 1
            tables.setdefault(table, set()).update(operations)
        target_class = target_method = label = None
        if value == '$this' and i+3 < len(tokens) and tokens[i+1][0] == '->':
            if tokens[i+3][0] == '(':
                target_class, target_method = node['class_name'], tokens[i+2][0]
            elif i+5 < len(tokens) and tokens[i+3][0] == '->' and tokens[i+5][0] == '(':
                target_class = properties.get(node['class_name'], {}).get('$'+tokens[i+2][0])
                target_method = tokens[i+4][0]
                label = '$this->' + tokens[i+2][0] + '->' + target_method
        elif kind == 'var' and i+3 < len(tokens) and tokens[i+1][0] == '->' and tokens[i+3][0] == '(':
            target_class = node['_types'].get(value)
            target_method = tokens[i+2][0]
            label = value + '->' + target_method
        elif kind == 'name' and i+3 < len(tokens) and tokens[i+1][0] == '::' and tokens[i+3][0] == '(':
            target_class = node['class_name'] if value in ('self', 'static') else resolve_class(value, node['_namespace'], node['_aliases'])
            target_method = tokens[i+2][0]
        elif value == 'app' and i+8 < len(tokens):
            values = [t[0] for t in tokens[i:i+9]]
            if values[1] == '(' and values[3:7] == ['::', 'class', ')', '->'] and values[8] == '(':
                target_class = resolve_class(values[2], node['_namespace'], node['_aliases'])
                target_method = values[7]
        if target_method:
            target = f'{target_class}::{target_method}' if target_class else None
            label = label or (f'{target_class}::{target_method}' if target_class else target_method)
            item = {'label': label, 'target': target if target in symbols else None}
            if item not in calls:
                calls.append(item)
    node.update({
        'guards': [{'line': n, 'code': c} for n, c in sorted(guards.items())],
        'writes': [{'line': n, 'code': c} for n, c in sorted(writes.items())],
        'tables': [{'table': name, 'operations': sorted(ops)} for name, ops in sorted(tables.items())],
        'statuses': sorted(statuses), 'calls': calls,
    })


def parse_routes(path, source):
    tokens, aliases = tokenize(source), imports(source)
    routes, warnings = [], []

    def walk(first, last, prefix='', name_prefix='', middleware=()):
        i = first
        while i < last:
            if tokens[i][0] != 'Route' or i+3 >= last or tokens[i+1][0] != '::':
                i += 1
                continue
            start, k, chain = i, i+2, []
            group_body = None
            while k+1 < last and tokens[k+1][0] == '(':
                method, op = tokens[k][0], k+1
                if method == 'group':
                    opening = next((x for x in range(op+1, last) if tokens[x][0] in ('{', ';')), None)
                    if opening is not None and tokens[opening][0] == '{':
                        closing = matching(tokens, opening, '{', '}')
                        group_body = (opening+1, closing)
                    break
                closing = matching(tokens, op)
                chain.append((method, tokens[op+1:closing]))
                k = closing+1
                if k < last and tokens[k][0] == '->':
                    k += 1
                else:
                    break
            if group_body:
                extra = next((literal(args[0]) for method, args in chain if method == 'prefix' and args and literal(args[0]) is not None), '')
                extra_name = next((literal(args[0]) for method, args in chain if method == 'name' and args), '')
                extra_mw = tuple(literal(t) for method, args in chain if method == 'middleware' for t in args if t[4] == 'string')
                walk(*group_body, '/'.join(p.strip('/') for p in (prefix, extra) if p.strip('/')), name_prefix+extra_name, middleware+extra_mw)
                i = group_body[1]+1
                continue
            if chain and chain[0][0] in ('get', 'post', 'put', 'patch', 'delete', 'options', 'any'):
                method, args = chain[0]
                route_path = literal(args[0]) if args else None
                if route_path is None:
                    warnings.append(f'{path}:{tokens[start][3]} — path dinamis belum terurai')
                    i = max(k, i+1)
                    continue
                handler = None
                for x in range(len(args)-4):
                    if args[x][4] == 'name' and [t[0] for t in args[x+1:x+4]] == ['::', 'class', ','] and args[x+4][4] == 'string':
                        handler = resolve_class(args[x][0], '', aliases) + '::' + literal(args[x+4])
                        break
                full_path = '/' + '/'.join(p.strip('/') for p in (prefix, route_path) if p.strip('/'))
                route_name = name_prefix + next((literal(a[0]) for m, a in chain if m == 'name' and a), '')
                route_mw = list(middleware) + [literal(t) for m, a in chain if m == 'middleware' for t in a if t[4] == 'string']
                rid = sha(f'{method}:{full_path}:{handler}:{path}'.encode())[:16]
                routes.append({'id': rid, 'http': method.upper(), 'path': full_path, 'name': route_name,
                               'entry': handler or 'Closure / handler dinamis', 'source': {'path': path, 'line': tokens[start][3]},
                               'middleware': route_mw})
                if handler is None:
                    warnings.append(f'{path}:{tokens[start][3]} — handler rute bukan array class/method; telusuri manual.')
            i = max(k, i+1)
    walk(0, len(tokens))
    return routes, warnings


def atomic_write(path, payload):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and (path.is_symlink() or path.is_junction()):
        raise ValueError(f'Tidak menulis melalui link: {path.name}')
    with tempfile.NamedTemporaryFile(dir=path.parent, suffix='.live-tmp', delete=False) as temp:
        temp.write(payload)
        temporary = Path(temp.name)
    os.replace(temporary, path)


class SourceMap:
    def __init__(self, root, port=8767):
        self.root = Path(root).resolve()
        self.out = self.root / 'docx'
        self.scope = load_sync(self.root)
        self.port = port
        self.access_token = secrets.token_urlsafe(32)
        self.version = None
        self.snapshot = None
        self.payload = b''
        self.html = b''
        self.lock = threading.Lock()
        self.closed = threading.Event()
        self.last_error = None

    def fingerprint(self):
        sources = self.scope.sources()
        inputs = {}
        files = ['docx/live.py', 'docx/sumber/alur-live.html', 'docx/model.json', 'docx/sinkron.json',
                 'docx/sumber/alur-operasional.json', 'docx/sumber/diagram-view.js']
        files.extend(p.relative_to(self.root).as_posix() for p in (self.out/'sumber/modul').glob('*.json'))
        for relative in files:
            path = self.root / relative
            if path.is_file():
                inputs[relative] = sha(path.read_bytes())
        return sources, sha(json_bytes({'sources': sources, 'inputs': inputs}))

    def bindings(self, symbols, sources):
        path = self.out / 'sumber/live-bindings.json'
        model_path, baseline_path = self.out/'model.json', self.out/'sinkron.json'
        if not model_path.exists() or not baseline_path.exists():
            return {}, {}
        model, baseline = json.loads(model_path.read_text(encoding='utf-8')), json.loads(baseline_path.read_text(encoding='utf-8'))
        key = sha(model_path.read_bytes() + baseline_path.read_bytes())
        if path.exists():
            old = json.loads(path.read_text(encoding='utf-8'))
            if old['reviewed_key'] == key:
                return old['notes'], old['sources']
        notes = {}
        for step in model['steps']:
            file, line = step['evidence'].rsplit(':', 1)
            if baseline['sources'].get(file) != sources.get(file):
                continue
            symbol = next((s['id'] for s in symbols.values() if s['path'] == file and s['line'] <= int(line) <= s['end']), None)
            if symbol:
                notes[step['id']] = {'symbol': symbol, **{k: step[k] for k in ('id', 'label', 'actor', 'before', 'after')}}
        atomic_write(path, json_bytes({'reviewed_key': key, 'notes': notes, 'sources': baseline['sources']}))
        return notes, baseline['sources']

    def business_journeys(self, symbols, routes, notes, reviewed_sources, sources):
        """Project the reviewed BUSINESS flows, not the technical callgraph, as primary UI."""
        path = self.out/'sumber/alur-operasional.json'
        model_path = self.out/'model.json'
        if not path.exists() or not model_path.exists():
            return [], 'Alur operasional belum dipetakan untuk proyek ini.'
        definition = json.loads(path.read_text(encoding='utf-8'))
        model = json.loads(model_path.read_text(encoding='utf-8'))
        steps = {s['id']: s for s in model['steps']}
        proofs = {}
        for package_path in sorted((self.out/'sumber/modul').glob('*.json')):
            package = json.loads(package_path.read_text(encoding='utf-8'))
            for proof in package.get('proofs', []):
                proofs.setdefault(proof['step_id'], []).append(proof)
        result, journey_ids = [], {j['id'] for j in definition['journeys']}
        for journey in definition['journeys']:
            ids = {s['id'] for s in journey['steps']}
            for link in journey['links']:
                if link['journey_id'] not in journey_ids:
                    raise ValueError(f'Tujuan alur tidak ditemukan: {link}')
            enriched = []
            for stage in journey['steps']:
                for target in stage['next'] + [b['next'] for b in stage['branches'] if b['next']]:
                    if target not in ids:
                        raise ValueError(f'Tujuan tahap bisnis tidak ditemukan: {target}')
                evidence, details, dependencies = [], [], set()
                for ref in stage['refs']:
                    if ref not in steps:
                        raise ValueError(f'Langkah bukti bisnis belum dipetakan: {ref}')
                    step = steps[ref]
                    file, _ = step['evidence'].rsplit(':', 1)
                    dependencies.add(file)
                    details.append({k: step[k] for k in ('id', 'label', 'actor', 'before', 'after')})
                    node_id = notes.get(ref, {}).get('symbol')
                    relevant_routes = [r for r in routes if node_id and node_id in r['node_ids']]
                    # Changes to reachable service/guard code must not silently re-approve prose.
                    for route in relevant_routes:
                        dependencies.add(route['source']['path'])
                        dependencies.update(symbols[s]['path'] for s in route['node_ids'])
                    if node_id and node_id in symbols:
                        node = symbols[node_id]
                        item = {'path': node['path'], 'line': node['line'], 'end': node['end'], 'node_ids': [node_id]}
                        if item not in evidence:
                            evidence.append(item)
                    for proof in proofs.get(ref, []):
                        proof_path = proof['path']
                        dependencies.add(proof_path)
                        if reviewed_sources.get(proof_path) != sources.get(proof_path):
                            continue  # Old line ranges cannot identify helpers after source relocation.
                        proof_node = next((n for n in symbols.values() if n['path'] == proof_path
                                           and n['line'] <= proof['start'] <= n['end']), None)
                        if proof_node:
                            item = {'path': proof_path, 'line': proof_node['line'], 'end': proof_node['end'],
                                    'node_ids': [proof_node['id']]}
                        elif reviewed_sources.get(proof_path) == sources.get(proof_path):
                            raw = (self.root/proof_path).read_text(encoding='utf-8-sig').splitlines()
                            item = {'path': proof_path, 'line': proof['start'], 'end': proof['end'], 'node_ids': [],
                                    'code': safe_code('\n'.join(raw[proof['start']-1:proof['end']]))}
                        else:
                            continue  # Never show shifted stale ranges as live proof.
                        if item not in evidence:
                            evidence.append(item)
                current = bool(evidence) and all(reviewed_sources.get(p) == sources.get(p) for p in dependencies)
                enriched.append({**stage, 'current': current, 'evidence': evidence, 'reviewed_details': details})
            result.append({**journey, 'steps': enriched})
        return result, definition['intro']

    def rebuild(self, force=False):
        sources, version = self.fingerprint()
        if not force and version == self.version:
            with self.lock:
                self.last_error = None
            return False
        symbols, properties, routes, warnings = {}, {}, [], []
        for relative in sources:
            if not relative.endswith('.php'):
                continue
            if relative == 'app/Http/Controllers/DemoSetupController.php':
                warnings.append('DemoSetupController tidak dipublikasikan: provisioning/demo dapat memuat nilai kredensial; rutenya hanya diinventarisasi.')
                continue
            if not (relative.startswith(('app/Http/', 'app/Services/', 'app/Models/')) or relative.startswith('routes/')):
                continue  # Do not expose console provisioning or seed credential literals.
            source = (self.root / relative).read_text(encoding='utf-8-sig')
            if relative.startswith('routes/'):
                parsed, notes = parse_routes(relative, source)
                routes.extend(parsed)
                warnings.extend(notes)
            else:
                parsed, deps = parse_file(relative, source)
                symbols.update(parsed)
                properties.update(deps)
        for symbol in symbols.values():
            analyze_symbol(symbol, properties, symbols)
        notes, reviewed_sources = self.bindings(symbols, sources)
        reachable_all = set()
        for route in routes:
            reachable, edges, queue = [], [], deque([route['entry']])
            seen = set()
            while queue:
                sid = queue.popleft()
                if sid in seen or sid not in symbols:
                    continue
                seen.add(sid)
                reachable.append(sid)
                for call in symbols[sid]['calls']:
                    if call['target']:
                        edges.append({'from': sid, 'to': call['target'], 'label': call['label']})
                        queue.append(call['target'])
            reachable_all.update(reachable)
            current = (reviewed_sources.get(route['source']['path']) == sources.get(route['source']['path'])
                       and all(reviewed_sources.get(symbols[s]['path']) == sources.get(symbols[s]['path']) for s in reachable))
            route['node_ids'], route['edges'] = reachable, edges
            route['notes'] = [{**{k: v for k, v in note.items() if k != 'symbol'}, 'current': current}
                              for note in notes.values() if note['symbol'] in seen]
            route['unknowns'] = ['Panah adalah pemanggilan yang terlihat secara statis, bukan urutan runtime, transisi status, atau bukti semua cabang dieksekusi.']
            if not reachable:
                route['unknowns'].append('Handler tidak terurai menjadi metode sumber lokal; rute tetap ditampilkan tanpa hubungan rekaan.')
            unresolved = sum(c['target'] is None for s in reachable for c in symbols[s]['calls'])
            if unresolved:
                route['unknowns'].append(f'{unresolved} pemanggilan framework/dinamis/vendor tidak ditelusuri; baca sumber metode untuk kondisi lengkap.')
        journeys, business_intro = self.business_journeys(symbols, routes, notes, reviewed_sources, sources)
        reachable_all.update(sid for j in journeys for s in j['steps'] for e in s['evidence'] for sid in e['node_ids'])
        public_symbols = {sid: {k: v for k, v in symbols[sid].items() if not k.startswith('_')} for sid in sorted(reachable_all)}
        snapshot = {
            'version': version, 'generated_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
            'files_count': len(sources), 'route_count': len(routes), 'symbols': public_symbols,
            'access_token': self.access_token, 'live_url': f'http://127.0.0.1:{self.port}/alur.html',
            'coverage': 'Rute web/V2 → handler → metode lokal yang dapat diurai; cabang guard, query tabel, status literal dan kode asli diperbarui otomatis. Bukan pembuktian runtime. Sumber secret/console/seed tidak dipublikasikan.',
            'warnings': warnings + ['Jika V2 cutover aktif, metode tulis legacy ditolak oleh V2Cutover; inventaris rute bukan jaminan endpoint bisa dijalankan. Nilai .env/runtime tidak dibaca.',
                                    'Status/kode akun yang ditampilkan adalah literal penulisan; konteks if/guard tetap harus dibaca. Nilai sensitif/identitas literal disamarkan.'],
            'routes': routes, 'journeys': journeys, 'business_intro': business_intro,
        }
        payload = json_bytes(snapshot)
        template = (self.out / 'sumber/alur-live.html').read_text(encoding='utf-8')
        if template.count('__SNAPSHOT_JSON__') != 1:
            raise ValueError('Template HTML harus mempunyai tepat satu placeholder snapshot')
        embedded = payload.decode().replace('<', '\\u003c').replace('>', '\\u003e').replace('&', '\\u0026')
        template = template.replace('__DIAGRAM_JS__', (self.out/'sumber/diagram-view.js').read_text(encoding='utf-8')
                                    if (self.out/'sumber/diagram-view.js').exists() else '')
        html = template.replace('__SNAPSHOT_JSON__', embedded).encode('utf-8')
        # A source save during extraction must not publish a mixed revision.
        if self.fingerprint() != (sources, version):
            return False
        md_path = self.out/'DIAGRAM.md'
        if md_path.exists() and not md_path.read_text(encoding='utf-8').startswith('<!-- Generated by docx/live.py;'):
            raise ValueError('Tidak menimpa DIAGRAM.md yang diedit/manual tanpa marker generator.')
        atomic_write(self.out / 'alur-live.json', payload)
        atomic_write(self.out / 'alur.html', html)
        atomic_write(md_path, diagram_markdown(journeys))
        with self.lock:
            self.snapshot, self.payload, self.html, self.version = snapshot, payload, html, version
            self.last_error = None
        return True

    def watch(self, interval):
        while not self.closed.wait(interval):
            try:
                if self.rebuild():
                    print(f'UPDATED {self.version[:12]} routes={self.snapshot["route_count"]}', flush=True)
            except (ValueError, OSError, KeyError, json.JSONDecodeError) as error:
                with self.lock:
                    self.last_error = 'Pembaruan ditahan: sumber sedang tidak lengkap/tidak terurai. Snapshot terakhir tetap ditampilkan. ' + str(error)
                print('WAIT_SOURCE ' + str(error), flush=True)


def handler_for(state):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *args):
            pass  # Never log token URLs or source contents.

        def reply(self, status, payload=b'', content_type='text/plain; charset=utf-8', etag=None, cors=False):
            self.send_response(status)
            self.send_header('Content-Type', content_type)
            self.send_header('Content-Length', str(len(payload)))
            self.send_header('Cache-Control', 'no-store')
            self.send_header('X-Content-Type-Options', 'nosniff')
            self.send_header('X-Frame-Options', 'DENY')
            self.send_header('Content-Security-Policy', "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'self' http://127.0.0.1:"+str(state.port)+"; img-src 'self' data:; frame-ancestors 'none'; base-uri 'none'")
            if etag:
                self.send_header('ETag', '"'+etag+'"')
            if cors:
                self.send_header('Access-Control-Allow-Origin', self.headers.get('Origin', 'null'))
                self.send_header('Access-Control-Allow-Methods', 'GET')
                self.send_header('Access-Control-Allow-Headers', 'If-None-Match')
                self.send_header('Vary', 'Origin')
            self.end_headers()
            if payload:
                self.wfile.write(payload)

        def do_OPTIONS(self):
            parsed = urlsplit(self.path)
            token = parse_qs(parsed.query).get('token', [''])[0]
            allowed_hosts = {f'127.0.0.1:{state.port}', f'localhost:{state.port}'}
            allowed_origins = {'null', f'http://127.0.0.1:{state.port}', f'http://localhost:{state.port}'}
            if (parsed.path != '/api/snapshot' or self.headers.get('Host') not in allowed_hosts
                    or self.headers.get('Origin') not in allowed_origins
                    or not token.isascii() or len(token) != len(state.access_token)
                    or not secrets.compare_digest(token, state.access_token)):
                return self.reply(403, b'Preflight tidak diizinkan')
            return self.reply(204, cors=True)

        def do_GET(self):
            hosts = {f'127.0.0.1:{state.port}', f'localhost:{state.port}'}
            if self.headers.get('Host') not in hosts:
                return self.reply(403, b'Host tidak diizinkan')
            parsed = urlsplit(self.path)
            if parsed.path == '/health':
                return self.reply(200, b'{"ok":true}', 'application/json')
            if parsed.path in ('/', '/alur.html'):
                with state.lock:
                    html = state.html
                return self.reply(200, html, 'text/html; charset=utf-8')
            if parsed.path != '/api/snapshot':
                return self.reply(404, b'Tidak ditemukan')
            token = parse_qs(parsed.query).get('token', [''])[0]
            origin = self.headers.get('Origin')
            origins = {None, 'null', f'http://127.0.0.1:{state.port}', f'http://localhost:{state.port}'}
            if (not token.isascii() or len(token) != len(state.access_token)
                    or not secrets.compare_digest(token, state.access_token) or origin not in origins):
                return self.reply(403, b'Akses snapshot tidak diizinkan')
            with state.lock:
                payload, version, error = state.payload, state.version, state.last_error
                if error:
                    snapshot = dict(state.snapshot)
                    snapshot['warnings'] = [error, *snapshot['warnings']]
                    snapshot['version'] = version + '-source-error'
                    payload = json_bytes(snapshot)
                    version = snapshot['version']
            if self.headers.get('If-None-Match', '').strip('"') == version:
                return self.reply(304, etag=version, cors=origin is not None)
            return self.reply(200, payload, 'application/json; charset=utf-8', version, origin is not None)
    return Handler


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--build', action='store_true', help='Build snapshot sekali tanpa server')
    cli.add_argument('--port', type=int, default=8767)
    cli.add_argument('--interval', type=float, default=1.0)
    args = cli.parse_args()
    if not 1 <= args.port <= 65535 or not 0.2 <= args.interval <= 60:
        cli.error('Port atau interval tidak sah')
    state = SourceMap(ROOT, args.port)
    server = None
    try:
        if not args.build:
            server = ThreadingHTTPServer(('127.0.0.1', args.port), handler_for(state))
            server.daemon_threads = True
        if not state.rebuild(force=True):
            raise ValueError('Sumber berubah selama build awal; jalankan lagi setelah penyimpanan selesai.')
        print(json.dumps({'url': f'http://127.0.0.1:{args.port}/alur.html', 'routes': state.snapshot['route_count'],
                          'methods': len(state.snapshot['symbols']), 'bytes': len(state.html), 'mode': 'build' if args.build else 'watch'}, ensure_ascii=False), flush=True)
        if args.build:
            return 0
        threading.Thread(target=state.watch, args=(args.interval,), daemon=True).start()
        server.serve_forever(poll_interval=0.3)
    except KeyboardInterrupt:
        return 0
    except (ValueError, OSError, KeyError) as error:
        print(str(error), file=sys.stderr)
        return 1
    finally:
        state.closed.set()
        if server:
            server.server_close()


if __name__ == '__main__':
    sys.exit(main())
